  function apply(){
    const list=document.querySelector('.verse-list');
    if(!list)return false;
    const cards=[...list.querySelectorAll('.verse-card')];
    if(cards.length<9)return false;

    cards.forEach(card=>{
      const title=(titleNode(card)?.textContent||'').trim();
      const key=Object.keys(verses).find(k=>norm(k)===norm(title));
      if(key) setVerse(card,key,verses[key]);
    });

    const thank=[...list.querySelectorAll('.verse-card')].find(c=>norm(titleNode(c)?.textContent)==='thank you, march');
    if(thank){
      const label=thank.querySelector('.verse-label-editable,.verse-number');
      if(label)label.textContent='Verse XI';
      if(!list.querySelector('.confession-final-act')) makeFinalAct(thank);
    }
    document.documentElement.dataset.confessionContent='v58';
    return true;
  }

  const start=()=>{
    if(apply())return;
    const mo=new MutationObserver(()=>{if(apply())mo.disconnect();});
    mo.observe(document.documentElement,{childList:true,subtree:true});
    setTimeout(()=>mo.disconnect(),15000);
  };
  if(document.readyState==='loading')document.addEventListener('DOMContentLoaded',start,{once:true});else start();
